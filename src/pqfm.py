"""
Projected Quantum Feature Map (PQFM) for corporate bond RFQ fill-prediction.

Implements the 1-D Heisenberg-chain ansatz described in the paper:
  - Global normalization → bounded tanh transform
  - Heisenberg Trotter-step unitaries (RXX + RYY + RZZ decomposition)
  - Fiducial-state initialization
  - 1-local Pauli expectation-value readout  (3N outputs for N qubits)

For N=109 qubits the full statevector (2^109 amplitudes) is infeasible; callers
should use the MPS-backed AerEstimatorV2 available in simulator_runner /
hardware_runner.  This module exposes the raw circuit-building primitives so
that both runners can share identical circuit logic.
"""

from __future__ import annotations

import numpy as np
from qiskit import QuantumCircuit
from qiskit.circuit.library import RXXGate, RYYGate, RZZGate
from qiskit.quantum_info import SparsePauliOp
from qiskit.primitives import StatevectorEstimator


# ---------------------------------------------------------------------------
# Normalization helpers
# ---------------------------------------------------------------------------

def normalize_features(
    X: np.ndarray,
    use_global: bool = True,
) -> tuple[np.ndarray, float, float]:
    """Normalize a batch of feature vectors with the paper's global scalar.

    The paper computes a single mean μ and standard deviation w over **all**
    values in the batch (i.e. across every event and every feature dimension)
    before applying the per-element shift/scale.

    Args:
        X: Feature matrix of shape ``(n_events, n_features)`` or a 1-D
            array of length ``n_features``.
        use_global: When ``True`` (default), μ and w are the mean and std of
            every element in *X*.  When ``False``, they are per-feature
            statistics (mean/std along axis=0); only the global path is used
            in the paper, but the flag is retained for ablation experiments.

    Returns:
        ``(X_normalized, mu, w)`` where *X_normalized* has the same shape as
        *X*, *mu* is the scalar (or array when ``use_global=False``) mean, and
        *w* is the scalar (or array) standard deviation.

    Note:
        w is clipped to a minimum of 1e-8 to guard against constant-feature
        degenerate batches.
    """
    if use_global:
        mu: float = float(np.mean(X))
        w: float = float(np.std(X))
        w = max(w, 1e-8)
    else:
        mu = np.mean(X, axis=0)  # type: ignore[assignment]
        w = np.std(X, axis=0)    # type: ignore[assignment]
        w = np.where(w < 1e-8, 1e-8, w)  # type: ignore[assignment]

    X_normalized = (X - mu) / w
    return X_normalized, mu, w


# ---------------------------------------------------------------------------
# Bounded transform
# ---------------------------------------------------------------------------

def apply_tanh_transform(X_tilde: np.ndarray) -> np.ndarray:
    """Map normalized features into the bounded interval (−2π/3, +2π/3).

    Paper formula (Eq. bounded transform):
        x_pqfm = (2π/3) · tanh(x̃)

    This ensures that the coupling constants fed into the Heisenberg
    Hamiltonian remain bounded, preventing the Trotter steps from rotating
    qubits through arbitrarily large angles.

    Args:
        X_tilde: Array of any shape containing normalized feature values.

    Returns:
        Array of the same shape with values in the open interval (−2π/3, 2π/3).

    Note:
        # Custom — Context7 found no library equivalent (paper formula)
    """
    return (2.0 * np.pi / 3.0) * np.tanh(X_tilde)


# ---------------------------------------------------------------------------
# Fiducial state
# ---------------------------------------------------------------------------

def build_fiducial_state(n_qubits: int, seed: int) -> QuantumCircuit:
    """Build a deterministic product fiducial state |ψ₀⟩ = ⊗ᵢ |φᵢ⟩.

    Each single-qubit state |φᵢ⟩ is generated by applying a random Ry(θ)
    followed by Rz(φ) rotation to |0⟩, where (θ, φ) ∈ [0, 2π)² are drawn
    from a seeded RNG.  The same seed always produces the same fiducial state.

    Args:
        n_qubits: Number of qubits N.
        seed: Integer seed for ``numpy.random.default_rng``.

    Returns:
        A :class:`~qiskit.QuantumCircuit` of size *n_qubits* that prepares the
        fiducial product state when applied to the |0…0⟩ computational basis.

    Note:
        # Custom — Context7 found no library equivalent
    """
    rng = np.random.default_rng(seed)
    thetas = rng.uniform(0.0, 2.0 * np.pi, size=n_qubits)
    phis = rng.uniform(0.0, 2.0 * np.pi, size=n_qubits)

    qc = QuantumCircuit(n_qubits, name="fiducial")
    for qubit in range(n_qubits):
        qc.ry(thetas[qubit], qubit)
        qc.rz(phis[qubit], qubit)
    return qc


# ---------------------------------------------------------------------------
# Heisenberg Trotter step
# ---------------------------------------------------------------------------

def build_heisenberg_trotter_step(
    n_qubits: int,
    couplings: np.ndarray,
    alpha: float,
    M: int,
) -> QuantumCircuit:
    """Build one Trotterized Heisenberg-chain evolution step.

    The Hamiltonian for bond j is::

        H_j(J_j) = J_j · (X_j X_{j+1} + Y_j Y_{j+1} + Z_j Z_{j+1})

    The exact two-qubit unitary for bond j is approximated as a product of
    three Pauli-pair rotations (first-order product-formula Trotterisation of
    the bond Hamiltonian — exact for each individual bond since the three
    terms in H_j do *not* commute globally, but this is the standard
    decomposition used in the paper's circuit):

        U_j(J_j) ≈ RXX(2θ) · RYY(2θ) · RZZ(2θ),   θ = α·J_j / (2M)

    The layer ordering follows the paper: **odd bonds first, then even bonds**
    (odd-even Suzuki–Trotter decomposition):
        - Odd bonds:  (1,2), (3,4), (5,6), …
        - Even bonds: (0,1), (2,3), (4,5), …

    Args:
        n_qubits: Number of qubits N.  Number of bonds = N−1.
        couplings: 1-D array of length N−1 containing {J_j} coupling values
            for this step.  ``couplings[j]`` is the coupling for bond j
            (connecting qubits j and j+1, 0-indexed).
        alpha: Global time/strength parameter α from the paper.
        M: Total number of Trotter steps in the full circuit (used to set the
            per-step angle θ = α·J_j / (2M)).

    Returns:
        A :class:`~qiskit.QuantumCircuit` implementing one complete odd-even
        Trotter step on *n_qubits* qubits.

    Note:
        # Custom — Context7 found no library equivalent (paper Eq. Heisenberg)
    """
    n_bonds = n_qubits - 1
    if len(couplings) != n_bonds:
        raise ValueError(
            f"couplings length {len(couplings)} != n_bonds {n_bonds}"
        )

    qc = QuantumCircuit(n_qubits, name="trotter_step")

    def _apply_bond(j: int) -> None:
        """Apply RXX·RYY·RZZ on bond (j, j+1)."""
        theta = alpha * float(couplings[j]) / (2.0 * M)
        qc.append(RXXGate(2.0 * theta), [j, j + 1])
        qc.append(RYYGate(2.0 * theta), [j, j + 1])
        qc.append(RZZGate(2.0 * theta), [j, j + 1])

    # Odd bonds: j = 1, 3, 5, …
    for j in range(1, n_bonds, 2):
        _apply_bond(j)

    # Even bonds: j = 0, 2, 4, …
    for j in range(0, n_bonds, 2):
        _apply_bond(j)

    return qc


# ---------------------------------------------------------------------------
# Full PQFM circuit
# ---------------------------------------------------------------------------

def build_pqfm_circuit(
    X_pqfm: np.ndarray,
    n_qubits: int,
    blocks: int,
    alpha: float,
    fiducial_seed: int,
) -> QuantumCircuit:
    """Assemble the full PQFM circuit for one preprocessed event vector.

    The circuit is::

        |ψ⟩ = (∏_{odd} U_j · ∏_{even} U_j)^M |ψ₀⟩

    where M = 2·blocks and |ψ₀⟩ is the fiducial product state.

    Feature assignment (1-indexed step k, 0-indexed bond j):

        J_j^{(k)} = X_pqfm[((k-1) · n_pairs + j) mod len(X_pqfm)]

    For blocks=1 (M=2) and len(X_pqfm)=2·n_pairs the two steps each consume
    exactly half of the input vector with no repetition.  For blocks=2 (M=4)
    the 216-element feature vector is reused cyclically across all 4 steps.

    Args:
        X_pqfm: 1-D array of PQFM-transformed coupling values, typically of
            length 2·n_pairs (= 216 for N=109).  Modulo indexing is used when
            M·n_pairs > len(X_pqfm).
        n_qubits: Number of qubits N.
        blocks: Number of circuit blocks; M = 2·blocks Trotter steps are
            applied.
        alpha: Global α parameter passed to each Trotter step.
        fiducial_seed: Integer seed for the fiducial state RNG.

    Returns:
        A :class:`~qiskit.QuantumCircuit` of size *n_qubits* ready for
        expectation-value estimation.
    """
    n_pairs = n_qubits - 1
    M = 2 * blocks
    feature_len = len(X_pqfm)

    qc = QuantumCircuit(n_qubits)

    # Fiducial state preparation
    qc.compose(build_fiducial_state(n_qubits, fiducial_seed), inplace=True)

    # M Trotter steps (k is 1-indexed to match the paper)
    for k in range(1, M + 1):
        # Gather couplings for this step with cyclic indexing
        indices = np.array(
            [((k - 1) * n_pairs + j) % feature_len for j in range(n_pairs)]
        )
        step_couplings = X_pqfm[indices]
        qc.compose(
            build_heisenberg_trotter_step(n_qubits, step_couplings, alpha, M),
            inplace=True,
        )

    return qc


# ---------------------------------------------------------------------------
# Observables
# ---------------------------------------------------------------------------

def build_observables(n_qubits: int) -> list[SparsePauliOp]:
    """Build the list of 3·N single-qubit Pauli observables.

    Returns observables in the order::

        [X₀, Y₀, Z₀, X₁, Y₁, Z₁, …, X_{N-1}, Y_{N-1}, Z_{N-1}]

    In Qiskit's convention the Pauli string is written with qubit 0 at the
    **rightmost** character position.  For qubit j out of N total qubits the
    Pauli string for operator P_j is therefore::

        'I' * (N - 1 - j) + P + 'I' * j

    Args:
        n_qubits: Number of qubits N.  Output list has length 3·N.

    Returns:
        List of :class:`~qiskit.quantum_info.SparsePauliOp` objects, one per
        observable, each acting on *n_qubits* qubits.
    """
    observables: list[SparsePauliOp] = []
    for qubit in range(n_qubits):
        prefix = "I" * (n_qubits - 1 - qubit)
        suffix = "I" * qubit
        for pauli_char in ("X", "Y", "Z"):
            pauli_str = prefix + pauli_char + suffix
            observables.append(SparsePauliOp.from_list([(pauli_str, 1.0)]))
    return observables


# ---------------------------------------------------------------------------
# Single-event noiseless transform
# ---------------------------------------------------------------------------

def transform_event_noiseless(
    x: np.ndarray,
    mu: float,
    w: float,
    n_qubits: int,
    blocks: int,
    alpha: float,
    fiducial_seed: int,
) -> np.ndarray:
    """Apply the full PQFM pipeline to a single preprocessed event vector.

    Pipeline::

        x  →  x̃ = (x − μ) / w  →  x_pqfm = (2π/3)·tanh(x̃)
           →  build_pqfm_circuit  →  ⟨ψ|O_i|ψ⟩ for i = 0 … 3N−1

    Uses :class:`~qiskit.primitives.StatevectorEstimator` (exact noiseless
    simulation).  For *n_qubits* > 20 the memory requirement grows as 2^N;
    prefer :class:`~simulator_runner.SimulatorRunner` (MPS backend) for the
    full 109-qubit circuit.

    Args:
        x: 1-D feature array for one event.  Must have length ≥ 2·(n_qubits−1)
            so that modulo cycling works sensibly.
        mu: Global mean scalar (from :func:`normalize_features`).
        w: Global std scalar (from :func:`normalize_features`).
        n_qubits: Number of qubits N.
        blocks: Circuit blocks parameter; M = 2·blocks Trotter steps.
        alpha: Global α parameter.
        fiducial_seed: Seed for the fiducial state RNG.

    Returns:
        1-D NumPy array of shape ``(3*n_qubits,)`` containing expectation
        values ⟨X₀⟩, ⟨Y₀⟩, ⟨Z₀⟩, …, ⟨Z_{N-1}⟩.
    """
    # Step 1 – normalize
    x_tilde = (x - mu) / w

    # Step 2 – bounded tanh transform
    x_pqfm = apply_tanh_transform(x_tilde)

    # Step 3 – build circuit
    circuit = build_pqfm_circuit(x_pqfm, n_qubits, blocks, alpha, fiducial_seed)

    # Step 4 – build observables
    observables = build_observables(n_qubits)

    # Step 5 – run StatevectorEstimator
    estimator = StatevectorEstimator()
    job = estimator.run([(circuit, observables)])
    result = job.result()
    evs: np.ndarray = result[0].data.evs

    # evs shape is (3*n_qubits,) when a list of observables is passed
    return np.asarray(evs, dtype=float)
